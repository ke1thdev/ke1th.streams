// Refresh the bundled artwork without changing the live catalog.
// Node 20+: npm run cache:artwork
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const api = 'https://tmdb-proxy.ke1th.dev';
const jobs = new Set();
const failures = [];
const today = new Date().toISOString().slice(0, 10);
const common = { language: 'en-US', include_adult: false, 'vote_count.gte': 1, 'vote_average.gte': 0.1, 'with_runtime.gte': 30, watch_region: 'PH', region: 'PH', page: 1 };

async function json(endpoint, params = {}) {
  const url = new URL(endpoint, api);
  Object.entries(params).forEach(([k, v]) => url.searchParams.set(k, String(v)));
  const response = await fetch(url, { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`${endpoint}: HTTP ${response.status}`);
  return response.json();
}

function add(file, size) {
  if (/^\/[A-Za-z0-9_-]+\.(?:jpg|png|webp)$/.test(file || '')) jobs.add(`${size}${file}`);
}

function collect(data) {
  for (const item of data.results || []) {
    add(item.poster_path, 'w500');
    add(item.backdrop_path || item.poster_path, 'w1280');
  }
}

async function parallel(items, fn, count = 6) {
  let next = 0;
  await Promise.all(Array.from({ length: count }, async () => {
    while (next < items.length) {
      const item = items[next++];
      try { await fn(item); } catch (error) { failures.push({ item: typeof item === 'string' ? item : item[0], error: error.message }); }
    }
  }));
}

const queries = [
  ['/trending/all/week'], ['/trending/all/day'], ['/trending/movie/week'], ['/trending/tv/week'],
  ['/movie/top_rated'], ['/tv/top_rated'],
  ['/discover/movie', { ...common, sort_by: 'primary_release_date.desc', 'primary_release_date.lte': today }],
  ['/discover/tv', { ...common, sort_by: 'first_air_date.desc', 'first_air_date.lte': today }]
];
for (const type of ['movie', 'tv']) {
  const dated = { ...common, [type === 'tv' ? 'first_air_date.lte' : 'primary_release_date.lte']: today };
  for (const genre of type === 'tv' ? [10759, 35, 10765, 16] : [28, 35, 878, 16]) queries.push([`/discover/${type}`, { ...dated, with_genres: genre, sort_by: 'popularity.desc' }]);
  queries.push([`/discover/${type}`, { ...dated, with_original_language: 'tl', without_companies: '149142|173083', without_keywords: '325693.2.9477', sort_by: 'popularity.desc' }]);
  queries.push([`/discover/${type}`, { ...dated, with_original_language: 'ja', with_genres: 16, sort_by: 'popularity.desc' }]);
  queries.push([`/discover/${type}`, { ...dated, with_watch_providers: 8, sort_by: 'popularity.desc' }]);
}
await parallel(queries, async ([endpoint, params]) => collect(await json(endpoint, params)), 4);

// Preserve artwork already cached by PHP, including cast/episodes/search results.
const artRoot = path.join(root, 'assets/imgs/tmdb');
await fs.mkdir(artRoot, { recursive: true });
for (const size of ['w200', 'w500', 'w1280']) {
  for (const entry of await fs.readdir(path.join(artRoot, size)).catch(() => [])) {
    if (/^[A-Za-z0-9_-]+\.(?:jpg|png|webp)$/.test(entry)) jobs.add(`${size}/${entry}`);
  }
}
let downloaded = 0;
await parallel([...jobs], async key => {
  const destination = path.join(artRoot, key);
  if ((await fs.stat(destination).catch(() => null))?.size > 100) return;
  const response = await fetch(`https://image.tmdb.org/t/p/${key}`, { signal: AbortSignal.timeout(20000) });
  if (!response.ok || !/^image\/(?:jpeg|png|webp)(?:;|$)/i.test(response.headers.get('content-type') || '')) throw new Error(`Image HTTP ${response.status}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  if (buffer.length < 100 || buffer.length > 8 * 1024 * 1024) throw new Error('Invalid image size');
  await fs.mkdir(path.dirname(destination), { recursive: true });
  await fs.writeFile(destination, buffer);
  downloaded++;
}, 6);

const bundled = [];
for (const size of ['w200', 'w500', 'w1280']) {
  for (const entry of await fs.readdir(path.join(artRoot, size)).catch(() => [])) {
    if (/^[A-Za-z0-9_-]+\.(?:jpg|png|webp)$/.test(entry)) bundled.push(`${size}/${entry}`);
  }
}
await fs.writeFile(path.join(root, 'assets/js/image-manifest.js'), `// Generated by npm run cache:artwork. Paths are relative to assets/imgs/tmdb/.\nwindow.LOCAL_ARTWORK = ${JSON.stringify(bundled.sort())};\n`);
console.log(JSON.stringify({ downloaded, bundled: bundled.length, failures }, null, 2));
